    flow(c, [(928, 590), (842, 590)])
    flow_label(c, 880, 578, "да", GREEN)
    end_event(c, 600, 590)
    flow(c, [(668, 590), (620, 590)])
    c.text(600, 632, "сдача на склад", 10.5, 600, MUTED)

    gateway(c, 960, 690, 64, "?")
    c.text(960, 748, "исправим?", 10.5, 600, MUTED)
    flow(c, [(960, 624), (960, 656)])
    flow_label(c, 946, 648, "нет", RED)

    task(c, 720, 652, 170, 70, ["Повторная", "шлифовка"])
    flow(c, [(926, 690), (892, 690)])
    flow_label(c, 910, 678, "да", ORANGE)
    flow(c, [(718, 687), (660, 687), (660, 470), (929, 470), (929, 457)], ORANGE, 1.8, "6 4")
    c.text(672, 462, "перешлифовка 4 %", 10.5, 600, ORANGE, "start")

    end_event(c, 1040, 690, None, color=RED)
    flow(c, [(994, 690), (1022, 690)], RED)
    c.text(1072, 678, "изолятор брака", 11, 600, RED, "start")
    c.text(1072, 694, "2,3 %", 11, 400, RED, "start")

    c.text(120, 572, "Передел: повторная шлифовка — 4 %,", 11.5, 600, INK2, "start")
    c.text(120, 594, "брак — 2,3 % (60 % — утилизация).", 11.5, 600, INK2, "start")
