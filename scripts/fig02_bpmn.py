    c.text(120, 648, "переналадка 20 мин.", 11.5, 400, MUTED, "start")

    legend(c, 52, 812, [("task", "задача"), ("event", "событие"), ("gw", "шлюз"),
                        ("line", "поток управления"), ("dash", "возврат на передел")], size=11)
    save(c, "f02_bpmn_asis.png")


