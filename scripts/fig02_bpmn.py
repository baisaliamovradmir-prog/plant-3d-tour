    lane2(c, 52, 282, 1336, 224, "Оператор ЧПУ")
    lane2(c, 52, 506, 1336, 256, "ОТК и склад")

    # --- Мастер участка
    start_event(c, 130, 214)
    c.text(130, 190, "заявка", 10.5, 600, MUTED)
    task(c, 176, 176, 206, 76, ["Планирование", "партии 20 шт"])
