from docx.shared import Cm, Pt

from docx_lib import (Doc, BODY_W, BLUE, INK, MUTED, _cell_margins, _cell_shade,
                      _no_borders, _set_font)


def code_block(d, text, size=8.2):
    t = d.d.add_table(rows=1, cols=1)
    _no_borders(t)
    _cell_margins(t, top=140, bottom=140, left=200, right=160)
    cell = t.rows[0].cells[0]
    cell.width = Cm(BODY_W)
    _cell_shade(cell, "F6F8FB")
    first = True
    for line in text.split("\n"):
        par = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        par.paragraph_format.space_after = Pt(0)
        par.paragraph_format.line_spacing = 1.15
        r = par.add_run(line)
        _set_font(r, name="Consolas", size=size, color=INK)
    d.d.add_paragraph().paragraph_format.space_after = Pt(2)


