# ---------------------------------------------------------------- activity
def activity_diagram():
    W, H = 1440, 600
    c = Canvas(W, H)
    header(c, "UML — диаграмма деятельности: «Проверить изменение на модели»",
           "Сценарий инженера-технолога: от выбора процесса до сохранённого сценария сравнения")

    def act(x, y, w, h, lines, fill=WHITE, stroke=LINE):
        c.rect(x, y, w, h, fill, stroke, 12, 1.6, shadow=True)
        if isinstance(lines, str):
            lines = [lines]
        lh = 12.5 * 1.3
        y0 = y + h / 2 - len(lines) * lh / 2 + 11
        for i, ln in enumerate(lines):
            c.text(x + w / 2, y0 + i * lh, ln, 12.5, 500, INK)

    start_event(c, 96, 232, r=14)
    c.text(96, 200, "начало", 10.5, 600, MUTED)
    act(130, 196, 150, 72, ["Открыть", "процесс"])
    act(310, 196, 150, 72, ["Задать", "параметры"])
