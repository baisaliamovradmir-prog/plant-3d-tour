# ---------------------------------------------------------------- sequence
def sequence_diagram():
    W, H = 1440, 860
    c = Canvas(W, H)
    header(c, "UML — диаграмма последовательности: запуск прогона",
           "Основной сценарий: пользователь меняет параметры и получает метрики на дашборде")

    lanes = [(150, "Пользователь"), (400, "Веб-приложение"), (650, "API (FastAPI)"),
             (900, "Сервис сценариев"), (1130, "Симулятор"), (1340, "БД PostgreSQL")]
    top, bottom = 150, 812
    for x, name in lanes:
        c.rect(x - 78, top - 34, 156, 44, "#EEF5FD", BLUE2, 8, 1.4)
        c.text(x, top - 8, name, 11.5, 700, BLUE)
        c.line(x, top + 10, x, bottom, "#B7C6D8", 1.3, "5 5")

    def msg(y, x1, x2, label, dashed=False, color=INK2, size=10.5):
        c.arrow(x1, y, x2, y, color, 1.6, 8, "5 4" if dashed else None)
        mx = (x1 + x2) / 2
        w = c.text_w(label, size, 600)
        c.rect(mx - w / 2 - 4, y - size - 4, w + 8, size + 6, WHITE, "none", 3, 0)
        c.text(mx, y - 4, label, size, 600, color)

    ys = [190, 228, 266, 304, 342, 376, 414, 452, 490, 528, 566, 616, 660, 700, 744, 780]
    msg(ys[0], 150, 400, "выбрать сценарий")
    msg(ys[1], 400, 650, "GET /scenarios/{id}")
    msg(ys[2], 650, 900, "getScenario(id)")
    msg(ys[3], 900, 1340, "SELECT s, p FROM scenario")
    msg(ys[4], 1340, 900, "строка + параметры", True)
    msg(ys[5], 900, 650, "ScenarioDTO", True)
    msg(ys[6], 650, 400, "200 OK (JSON)", True, GREEN)
    msg(ys[7], 400, 150, "формы заполнены", True, GREEN)
    msg(ys[8], 150, 400, "«Запустить прогон»")
    msg(ys[9], 400, 650, "POST /runs")
    msg(ys[10], 650, 1130, "run(model, params)")
    msg(ys[11], 650, 1340, "INSERT run (status=queued)", False, MUTED)

    # self-message
    c.line(1130, 566, 1230, 566, INK2, 1.6)
    c.line(1230, 566, 1230, 592, INK2, 1.6)
    c.arrow(1230, 592, 1134, 592, INK2, 1.6)
    c.text(1240, 582, "DES: 5 × 26 суток", 10.5, 600, INK2, "start")

    msg(ys[12], 1130, 650, "метрики + уверенность", True, GREEN)
    msg(ys[13], 650, 1340, "UPDATE run (status=done)")
    msg(ys[14], 650, 400, "200 OK: runId", True, GREEN)
    msg(ys[15], 400, 150, "дашборд с метриками", True, GREEN)

    c.text(150, 846, "Пунктир — ответное сообщение", 10.5, 400, MUTED, "start")

    save(c, "f07_sequence.png")


