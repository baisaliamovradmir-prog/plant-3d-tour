             ["processes", "process_nodes", "1 : N", "Каскадное удаление вместе с процессом"],
             ["processes", "process_edges", "1 : N", "Каскадное удаление вместе с процессом"],
             ["process_nodes", "process_edges", "1 : N", "Запрет удаления узла, на который есть связь"],
             ["processes", "resources", "1 : N", "Каскадное удаление"],
             ["processes", "scenarios", "1 : N", "Запрет удаления процесса с опубликованными сценариями"],
             ["scenarios", "scenarios", "1 : N (self)", "База сравнения — ссылка, удаление запрещено"],
             ["scenarios", "runs", "1 : N", "Каскадное удаление прогонов вместе со сценарием"],
             ["runs", "run_metrics", "1 : N", "Каскадное удаление"],
             ["metrics", "run_metrics", "1 : N", "Запрет удаления метрики, используемой в прогонах"],
             ["processes", "tours", "1 : N", "Запрет удаления процесса с опубликованным туром"],
             ["tours", "locations", "1 : N", "Каскадное удаление"],
             ["locations", "pois", "1 : N", "Каскадное удаление"],
             ["cases", "pois", "1 : N", "Set NULL: точка остаётся без кейса"],
             ["media", "pois", "1 : N", "Set NULL: карточка остаётся без медиа"],
